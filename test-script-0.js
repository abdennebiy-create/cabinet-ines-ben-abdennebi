      // ================================================================
      // GO BACK — Fixed navigation
      // ================================================================
      goBack() {
        if (this.state.history.length === 0) return;

        // Pop last history entry (the step we are going back TO)
        const lastEntry = this.state.history.pop();
        this.state.isComplete = false;
        this.state.finalDossier = null;

        // Determine which turn to go back to based on the popped history
        const prevTurn = lastEntry.turn;
        this.state.turn = prevTurn;

        // Restore state based on the turn we are going back to
        if (prevTurn === 1) {
          // Reset everything to start
          this.state.history = [];
          this.state.turn = 1;
          this.state.target = null;
          this.state.previousSelection = '';
          this.state.selectedConditions = [];
          this.state.weightGoal = null;
          this.state.track = null;
          this.state.deepDiveQueue = [];
          this.renderInitialTurn();
          return;
        }

        if (prevTurn === 2) {
          this.state.sex = null;
          this.state.profileAnswer = null;
        } else if (prevTurn === 3) {
          this.state.selectedConditions = [];
          this.state.track = null;
        } else if (prevTurn === 4) {
          this.state.weightGoal = null;
        } else if (prevTurn === 5) {
          if (lastEntry.deepDiveKey) {
            this.state.deepDiveQueue.unshift(lastEntry.deepDiveKey);
          }
        }

        const previousHistoryEntry = this.state.history[this.state.history.length - 1];
        this.state.previousSelection = previousHistoryEntry ? previousHistoryEntry.selection : '';

        this.renderTurnByNumber(prevTurn);
      },

